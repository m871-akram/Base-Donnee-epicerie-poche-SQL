-- TABLE PRODUCTEUR
CREATE TABLE PRODUCTEUR (
    IDPRODUCTEUR      NUMBER PRIMARY KEY NOT NULL,
    NOMPRODUCTEUR     VARCHAR(222) NOT NULL,
    ADRPRODUCTEUR     VARCHAR(222),
    LATITUDE          NUMBER,
    LONGITUDE         NUMBER
);

-- TABLE COORDONNEEPRODUCTEUR
CREATE TABLE COORDONNEEPRODUCTEUR (
    IDPRODUCTEUR NUMBER NOT NULL,
    COORDONNEEPRODUCTEUR VARCHAR(222) NOT NULL,
    VALEURCOORDONNEE  VARCHAR(222) NOT NULL,
    CONSTRAINT PK_COORDONNEEPRODUCTEUR
       PRIMARY KEY (IDPRODUCTEUR, COORDONNEEPRODUCTEUR),
    CONSTRAINT FK_COORDPROD_PRODUCTEUR
       FOREIGN KEY (IDPRODUCTEUR)
       REFERENCES PRODUCTEUR(IDPRODUCTEUR)
       ON DELETE CASCADE
);

-- TABLE ACTIVITE
CREATE TABLE ACTIVITE (
    TYPEACTIVITE VARCHAR2(50) PRIMARY KEY
);

-- RELATION POSSÈDE
CREATE TABLE POSSEDE (
    TYPEACTIVITE VARCHAR2(50),
    IDPRODUCTEUR   NUMBER,
    PRIMARY KEY (TYPEACTIVITE, IDPRODUCTEUR),
    FOREIGN KEY (TYPEACTIVITE) REFERENCES ACTIVITE(TYPEACTIVITE)
     ON DELETE CASCADE,
    FOREIGN KEY (IDPRODUCTEUR) REFERENCES PRODUCTEUR(IDPRODUCTEUR)
     ON DELETE CASCADE
);

-- TABLE PRODUIT
CREATE TABLE PRODUIT (
    IDPRODUIT NUMBER PRIMARY KEY,
    NOMPRODUIT VARCHAR2(222) NOT NULL,
    CATEGORIEPRODUIT VARCHAR2(222),
    DESCRIPT VARCHAR2(300),
    IDPRODUCTEUR NUMBER NOT NULL,
    DISPONIBILITE VARCHAR2(50),
    MODECOND VARCHAR2(20)
        CHECK (MODECOND IN ('VRAC','PRE','LES_DEUX')),
    FOREIGN KEY (IDPRODUCTEUR) REFERENCES PRODUCTEUR(IDPRODUCTEUR)
);

-- TABLE CARACTERISTIQUE
CREATE TABLE CARACTERISTIQUE (
    IDPRODUIT NUMBER,
    NOMCARACTERISTIQUE VARCHAR2(100),
    VALCARACTERISTIQUE VARCHAR2(200),
    PRIMARY KEY (IDPRODUIT, NOMCARACTERISTIQUE),
    FOREIGN KEY (IDPRODUIT) REFERENCES PRODUIT(IDPRODUIT) ON DELETE CASCADE
);

-- TABLE VRAC
CREATE TABLE VRAC (
    IDPRODUIT NUMBER PRIMARY KEY,
    PRIXACHATVRAC NUMBER,
    PRIXKGVRAC NUMBER,
    PRIXVENTEVRAC NUMBER,
    FOREIGN KEY (IDPRODUIT) REFERENCES PRODUIT(IDPRODUIT) ON DELETE CASCADE
);

-- TABLE PRECOND
CREATE TABLE PRECOND (
    IDPRODUIT   NUMBER PRIMARY KEY,
    POIDSFIXE   NUMBER,
    PRIXACHATP  NUMBER,
    PRIXVENTEP  NUMBER,
    FOREIGN KEY (IDPRODUIT) REFERENCES PRODUIT(IDPRODUIT) ON DELETE CASCADE
);

-- TABLE PERIODE
CREATE TABLE PERIODE (
    IDPERIODE    NUMBER PRIMARY KEY,
    DEBUTPERIODE DATE NOT NULL,
    FINPERIODE   DATE NOT NULL
    CONSTRAINT VERIFDATE CHECK (DEBUTPERIODE < FINPERIODE)
);

-- TABLE PERIODE_DISPONIBILITE
CREATE TABLE PERIODE_DISPONIBILITE (
    IDPRODUIT  NUMBER,
    IDPERIODE  NUMBER,
    PRIMARY KEY (IDPRODUIT, IDPERIODE),
    FOREIGN KEY (IDPRODUIT) REFERENCES PRODUIT(IDPRODUIT) ON DELETE CASCADE,
    FOREIGN KEY (IDPERIODE) REFERENCES PERIODE(IDPERIODE) ON DELETE CASCADE
);

-- TABLE CONTENANT
CREATE TABLE CONTENANT (
    IDCONTENANT   NUMBER PRIMARY KEY,
    TYPECONTENANT VARCHAR2(50),
    CAPACCONTENANT NUMBER,
    UNITECONTENANT VARCHAR2(10) CHECK (UNITECONTENANT IN ('LITRE','GRAMME')),
    STOCKDISPOCONTENANT NUMBER,
    CARACTCONTENANT VARCHAR2(50) CHECK (CARACTCONTENANT IN ('JETABLE','REUTILISABLE')),
    PRIXVENTECONTENANT  NUMBER
);

-- TABLE LOT_PRODUIT
CREATE TABLE LOT_PRODUIT (
    IDLOTPRODUIT NUMBER PRIMARY KEY,
    IDPRODUIT NUMBER NOT NULL,
    QUANTITESTOCKLOT  NUMBER,
    UNITESTOCKLOT VARCHAR2(20) CHECK (UNITESTOCKLOT IN ('Kg','Unité')),
    DATERECEPTION DATE,
    DATEPEREMPTION DATE,
    TYPEDATE VARCHAR2(10) CHECK (TYPEDATE IN ('DLC','DLUO')),
    FOREIGN KEY (IDPRODUIT) REFERENCES PRODUIT(IDPRODUIT) ON DELETE CASCADE,
    CONSTRAINT LOTPRODUITDATE CHECK (DATEPEREMPTION >= DATERECEPTION)
);

-- TABLE LOT_CONTENANT
CREATE TABLE LOT_CONTENANT (
    IDLOTCONTENANT NUMBER PRIMARY KEY,
    IDCONTENANT NUMBER NOT NULL,
    QUANTITESTOCKLOT NUMBER,
    DATERECEPTION DATE,
    FOREIGN KEY (IDCONTENANT) REFERENCES CONTENANT(IDCONTENANT) ON DELETE CASCADE
);

-- TABLE PERTE
CREATE TABLE PERTE (
    IDPERTE NUMBER PRIMARY KEY,
    ELEMPERDU VARCHAR2(20),
    NATUREPERTE VARCHAR2(50),
    DATEPERTE DATE,
    QUANTITEPERTE NUMBER
);

-- TABLE PRODUIT_PERDU
CREATE TABLE PRODUIT_PERDU (
    IDPRODUIT NUMBER,
    IDPERTE   NUMBER,
    PRIMARY KEY (IDPRODUIT, IDPERTE),
    FOREIGN KEY (IDPRODUIT) REFERENCES PRODUIT(IDPRODUIT)ON DELETE CASCADE,
    FOREIGN KEY (IDPERTE) REFERENCES PERTE(IDPERTE) ON DELETE CASCADE
);

-- TABLE CONTENANT_PERDU
CREATE TABLE CONTENANT_PERDU (
    IDCONTENANT NUMBER,
    IDPERTE     NUMBER,
    PRIMARY KEY (IDCONTENANT, IDPERTE),
    FOREIGN KEY (IDCONTENANT) REFERENCES CONTENANT(IDCONTENANT) ON DELETE CASCADE,
    FOREIGN KEY (IDPERTE) REFERENCES PERTE(IDPERTE) ON DELETE CASCADE
);

-- TABLE CLIENT
CREATE TABLE CLIENT (
    IDCLIENT NUMBER PRIMARY KEY,
    ANONYME  NUMBER DEFAULT 1,
    CONSTRAINT CLIENTANONYME CHECK (ANONYME IN (0,1))
);

-- TABLE INFORMATION_CLIENT
CREATE TABLE INFORMATION_CLIENT (
    EMAILCLIENT VARCHAR2(100) PRIMARY KEY,
    NOMCLIENT   VARCHAR2(100),
    PRENOMCLIENT VARCHAR2(100),
    NUMTELCLIENT VARCHAR2(40),
    IDCLIENT    NUMBER UNIQUE,
    CONSTRAINT INFCLIENT UNIQUE (IdClient),
    FOREIGN KEY (IDCLIENT) REFERENCES CLIENT(IDCLIENT) ON DELETE CASCADE
);

-- TABLE ADRESSE
CREATE TABLE ADRESSE (
    IDADRESSE       NUMBER PRIMARY KEY NOT NULL,
    ADRESSEPOSTALE VARCHAR2(200),
    VILLE VARCHAR2(100),
    RUE VARCHAR2(100),
    PAYS  VARCHAR2(80),
    IDCLIENT NUMBER NOT NULL,
    FOREIGN KEY (IDCLIENT) REFERENCES CLIENT(IDCLIENT) ON DELETE CASCADE
);

-- TABLE COMMANDE
CREATE TABLE COMMANDE (
    IDCOMMANDE    NUMBER PRIMARY KEY,
    DATECOMMANDE  DATE,
    HEURECOMMANDE VARCHAR2(12),
    STATUT        VARCHAR2(30),
    IDCLIENT      NUMBER NOT NULL,
    FOREIGN KEY (IDCLIENT) REFERENCES CLIENT(IDCLIENT),
    CONSTRAINT VERIFSTATUT CHECK (
        Statut IN ('En préparation', 'Prête', 'En livraison', 'Récupérée', 'Livrée', 'Annulée')
    )
);

-- TABLE LIGNE_COMMANDE
CREATE TABLE LIGNE_COMMANDE (
    IDCOMMANDE        NUMBER NOT NULL,
    IDLIGNECOMMANDE   NUMBER,
    IDPRODUIT         NUMBER NOT NULL,
    QUANTITECOMMANDE  NUMBER,
    UNITECOMMANDE     VARCHAR2(20),
    PRIXUNITAIRE      NUMBER,
    SOUSTOTAL         NUMBER,
    MODEPAIEMENT      VARCHAR2(20)
        CHECK (MODEPAIEMENT IN ('EN LIGNE','EN BOUTIQUE')),
    PRIMARY KEY (IDCOMMANDE, IDLIGNECOMMANDE),
    FOREIGN KEY (IDCOMMANDE) REFERENCES COMMANDE(IDCOMMANDE),
    FOREIGN KEY (IDPRODUIT) REFERENCES PRODUIT(IDPRODUIT)
);

-- TABLE RETRAIT_BOUTIQUE
CREATE TABLE RETRAIT_BOUTIQUE (
    IDRETRAITBOUTIQUE NUMBER PRIMARY KEY NOT NULL,
    IDCOMMANDE        NUMBER UNIQUE,
    FOREIGN KEY (IDCOMMANDE) REFERENCES COMMANDE(IDCOMMANDE)
);

-- TABLE LIVRAISON_DOMICILE
CREATE TABLE LIVRAISON_DOMICILE (
    IDLIVRAISONDOMICILE NUMBER PRIMARY KEY NOT NULL,
    IDCOMMANDE          NUMBER UNIQUE,
    FRAISLIVRAISON      NUMBER,
    DATELIVRAISONESTIMEE DATE,
    IDADRESSE           NUMBER,
    FOREIGN KEY (IDCOMMANDE) REFERENCES COMMANDE(IDCOMMANDE),
    FOREIGN KEY (IDADRESSE) REFERENCES ADRESSE(IDADRESSE)
);

-- TABLE VRAC_UTILISE
CREATE TABLE VRAC_UTILISE (
    IDCONTENANT NUMBER,
    IDPRODUIT   NUMBER,
    PRIMARY KEY (IDCONTENANT, IDPRODUIT),
    FOREIGN KEY (IDCONTENANT) REFERENCES CONTENANT(IDCONTENANT) ON DELETE CASCADE,
    FOREIGN KEY (IDPRODUIT)   REFERENCES VRAC(IDPRODUIT)ON DELETE CASCADE
);


